# --- Drive scenario (iteration 10): launch with the 2-step, flat-shifted up to 3rd gear ---

DRIVE_FILE_NAME = "i6_30_na_drive.csv"
DRIVE_LAUNCH = LaunchSettings(
    enabled=True, launch_speed_rad_s=units.rpm_to_rad_s(4000.0), retard_deg=10.0, flat_shift=True
)
DRIVE_DURATION_S = 10.0
DRIVE_THROTTLE_FROM_S = 0.5
DRIVE_CLUTCH_UP_S = 2.5
DRIVE_SHIFT_RPM = 6500.0
DRIVE_TOP_GEAR = 3
DRIVE_SAMPLE_STEPS = 50  # one row every 50 ms
DRIVE_COLUMNS = (
    "time_s",
    "speed_rpm",
    "vehicleSpeed_kmh",
    "gear",
    "clutchEngagement",
    "clutchLocked",
    "launchActive",
    "sparkCut",
    "flatShift",
    "clutchTorque_Nm",
    "catalyst_degC",
)


def drive_shift_due(state: CarState) -> bool:
    """Upshift rule of the scenario: at the shift speed with a locked clutch, up to 3rd."""
    drivetrain = state.drivetrain
    return (
        units.rad_s_to_rpm(state.engine.speed_rad_s) >= DRIVE_SHIFT_RPM
        and drivetrain.clutch_state is ClutchState.LOCKED
        and 1 <= drivetrain.gear < DRIVE_TOP_GEAR
    )


def drive_rows(definition: EngineDefinition) -> list[list[float]]:
    car = CarSimulation(
        definition, replace(Tune.from_tables(definition.tables), launch=DRIVE_LAUNCH)
    )
    car.drivetrain.set_clutch_pedal(True)
    car.drivetrain.shift(1)
    steps = round(DRIVE_DURATION_S / car.engine.time_step_s)
    clutch_up_step = round(DRIVE_CLUTCH_UP_S / car.engine.time_step_s)
    throttle_step = round(DRIVE_THROTTLE_FROM_S / car.engine.time_step_s)
    rows: list[list[float]] = []
    for step in range(steps):
        if step == clutch_up_step:
            car.drivetrain.set_clutch_pedal(False)
        state = car.step(1.0 if step >= throttle_step else 0.0)
        if drive_shift_due(state):
            car.drivetrain.shift(state.drivetrain.gear + 1)
        if (step + 1) % DRIVE_SAMPLE_STEPS == 0:
            drivetrain = state.drivetrain
            command = state.engine.command
            rows.append(
                [
                    state.engine.time_s,
                    units.rad_s_to_rpm(state.engine.speed_rad_s),
                    units.ms_to_kmh(drivetrain.vehicle_speed_m_s),
                    float(drivetrain.gear),
                    drivetrain.clutch_engagement,
                    1.0 if drivetrain.clutch_state is ClutchState.LOCKED else 0.0,
                    1.0 if command.launch_active else 0.0,
                    1.0 if command.spark_cut else 0.0,
                    1.0 if command.flat_shift_active else 0.0,
                    drivetrain.clutch_torque_nm,
                    units.kelvin_to_celsius(state.engine.catalyst_temperature_k),
                ]
            )
    return rows


def render_drive_csv(engine_id: str = "i6_30_na") -> str:
    definition = load_engine(engine_path(engine_id))
    buffer = io.StringIO()
    buffer.write(f"# engine: {engine_id} (shared/engines/{engine_id}.json)\n")
    buffer.write(
        f"# 1st gear, clutch pressed, full throttle from {DRIVE_THROTTLE_FROM_S} s (2-step "
        f"4000 1/min, 10 deg), clutch up at {DRIVE_CLUTCH_UP_S} s, flat-shifted at "
        f"{DRIVE_SHIFT_RPM:.0f} 1/min up to gear {DRIVE_TOP_GEAR}; 1 ms steps, row every 50 ms\n"
    )
    buffer.write("# generated by lab: python -m tuning_lab.golden (do not edit by hand)\n")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(DRIVE_COLUMNS)
    for row in drive_rows(definition):
        writer.writerow([f"{value:.{DECIMALS}f}" for value in row])
    return buffer.getvalue()


def write_text_golden(file_name: str, text: str, directory: Path = GOLDEN_DIR) -> Path:
    path = directory / file_name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


