"""Golden files: reference results for the C++ port (docs/plan.md iteration 2 and 4).

Format: CSV, comment lines start with '#', the header row names every column with its unit.
Regenerate with:  .venv/bin/python -m tuning_lab.golden
The test tests/test_golden.py fails when the committed file no longer matches the model.
"""

import csv
import io
from dataclasses import dataclass, replace
from pathlib import Path

from tuning_lab import units
from tuning_lab.car import CarSimulation, CarState
from tuning_lab.drivetrain import ClutchState
from tuning_lab.dyno import SweepResult, run_sweep
from tuning_lab.ecu import LaunchSettings, OverrunSettings, Tune
from tuning_lab.engine_definition import EngineDefinition, load_engine
from tuning_lab.paths import GOLDEN_DIR, engine_path
from tuning_lab.roller import run_roller
from tuning_lab.simulation import EngineSimulation


@dataclass(frozen=True)
class GoldenSweepSpec:
    engine_id: str
    speed_from_rpm: float
    speed_to_rpm: float
    rate_rpm_s: float
    throttle: float
    sample_step_rpm: float

    @property
    def file_name(self) -> str:
        return f"{self.engine_id}_sweep.csv"


I6_30_NA_SWEEP = GoldenSweepSpec(
    engine_id="i6_30_na",
    speed_from_rpm=1000.0,
    speed_to_rpm=7000.0,
    rate_rpm_s=300.0,
    throttle=1.0,
    sample_step_rpm=100.0,
)

COLUMNS = (
    "speedSetpoint_rpm",
    "speed_rpm",
    "torque_Nm",
    "engineTorque_Nm",
    "power_kW",
    "bmep_bar",
    "map_kPa",
    "lambda",
    "ignition_degBTDC",
    "airflow_kg_s",
    "egt_degC",
)
DECIMALS = 6


def sweep_rows(result: SweepResult, definition: EngineDefinition) -> list[list[float]]:
    """Converts a sweep to the user-facing units of the CSV columns."""
    bmep = result.bmep_pa(definition.displacement_m3)
    return [
        [
            units.rad_s_to_rpm(float(result.setpoint_rad_s[i])),
            units.rad_s_to_rpm(float(result.speed_rad_s[i])),
            float(result.measured_torque_nm[i]),
            float(result.engine_torque_nm[i]),
            units.w_to_kw(float(result.power_w[i])),
            units.pa_to_bar(float(bmep[i])),
            units.pa_to_kpa(float(result.manifold_pressure_pa[i])),
            float(result.lambda_actual[i]),
            float(result.ignition_deg[i]),
            float(result.air_mass_flow_kg_s[i]),
            units.kelvin_to_celsius(float(result.exhaust_temperature_k[i])),
        ]
        for i in range(len(result.setpoint_rad_s))
    ]


def render_golden_csv(spec: GoldenSweepSpec) -> str:
    definition = load_engine(engine_path(spec.engine_id))
    result = run_sweep(
        definition,
        spec.speed_from_rpm,
        spec.speed_to_rpm,
        rate_rpm_s=spec.rate_rpm_s,
        throttle=spec.throttle,
        sample_step_rpm=spec.sample_step_rpm,
    )
    buffer = io.StringIO()
    buffer.write(f"# engine: {spec.engine_id} (shared/engines/{spec.engine_id}.json)\n")
    buffer.write(
        f"# full-load dyno sweep {spec.speed_from_rpm:.0f}-{spec.speed_to_rpm:.0f} 1/min "
        f"at {spec.rate_rpm_s:.0f} 1/min/s, throttle {spec.throttle}, time step 1 ms, "
        f"settle 3 s\n"
    )
    buffer.write("# generated by lab: python -m tuning_lab.golden (do not edit by hand)\n")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(COLUMNS)
    for row in sweep_rows(result, definition):
        writer.writerow([f"{value:.{DECIMALS}f}" for value in row])
    return buffer.getvalue()


def write_golden(spec: GoldenSweepSpec, directory: Path = GOLDEN_DIR) -> Path:
    path = directory / spec.file_name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_golden_csv(spec), encoding="utf-8")
    return path


# --- Overrun scenario (iteration 7b): free-revving tip-in, then lift-off with a pops tune ---

OVERRUN_FILE_NAME = "i6_30_na_overrun.csv"
OVERRUN_SETTINGS = OverrunSettings(fuel_cut=False, retard_deg=35.0, enrichment=0.1)
OVERRUN_DURATION_S = 6.0
OVERRUN_TIP_IN_S = (0.5, 1.3)  # full throttle in this window, closed otherwise
OVERRUN_SAMPLE_STEPS = 50  # one row every 50 ms
OVERRUN_COLUMNS = (
    "time_s",
    "speed_rpm",
    "map_kPa",
    "throttle",
    "fuelCut",
    "overrunFueling",
    "ignition_degBTDC",
    "lateCombustion",
    "egt_degC",
    "catalyst_degC",
    "engineTorque_Nm",
)


def overrun_throttle(time_s: float) -> float:
    start, end = OVERRUN_TIP_IN_S
    return 1.0 if start <= time_s < end else 0.0


def overrun_rows(definition: EngineDefinition) -> list[list[float]]:
    """Simulates the overrun scenario without a brake and samples it every 50 ms."""
    tune = replace(Tune.from_tables(definition.tables), overrun=OVERRUN_SETTINGS)
    simulation = EngineSimulation(definition, tune)
    steps = round(OVERRUN_DURATION_S / simulation.time_step_s)
    rows: list[list[float]] = []
    for step in range(steps):
        state = simulation.step(overrun_throttle(step * simulation.time_step_s), 0.0)
        if (step + 1) % OVERRUN_SAMPLE_STEPS == 0:
            rows.append(
                [
                    state.time_s,
                    units.rad_s_to_rpm(state.speed_rad_s),
                    units.pa_to_kpa(state.manifold_pressure_pa),
                    state.throttle,
                    1.0 if state.command.fuel_cut else 0.0,
                    1.0 if state.command.overrun_fueling else 0.0,
                    state.command.ignition_deg,
                    state.engine.late_combustion_fraction,
                    units.kelvin_to_celsius(state.engine.exhaust_temperature_k),
                    units.kelvin_to_celsius(state.catalyst_temperature_k),
                    state.engine.brake_torque_nm,
                ]
            )
    return rows


def render_overrun_csv(engine_id: str = "i6_30_na") -> str:
    definition = load_engine(engine_path(engine_id))
    buffer = io.StringIO()
    buffer.write(f"# engine: {engine_id} (shared/engines/{engine_id}.json)\n")
    buffer.write(
        f"# free running, full throttle {OVERRUN_TIP_IN_S[0]}-{OVERRUN_TIP_IN_S[1]} s, then "
        f"lift-off; overrun: fuel cut off, retard {OVERRUN_SETTINGS.retard_deg} deg, "
        f"enrichment {OVERRUN_SETTINGS.enrichment}; time step 1 ms, row every 50 ms\n"
    )
    buffer.write("# generated by lab: python -m tuning_lab.golden (do not edit by hand)\n")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(OVERRUN_COLUMNS)
    for row in overrun_rows(definition):
        writer.writerow([f"{value:.{DECIMALS}f}" for value in row])
    return buffer.getvalue()


def write_overrun_golden(directory: Path = GOLDEN_DIR) -> Path:
    path = directory / OVERRUN_FILE_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_overrun_csv(), encoding="utf-8")
    return path


# --- Launch scenario (iteration 7c): 2-step held at full throttle, then released ---

LAUNCH_FILE_NAME = "i6_30_na_launch.csv"
LAUNCH_SETTINGS = LaunchSettings(
    enabled=True, launch_speed_rad_s=units.rpm_to_rad_s(4000.0), retard_deg=10.0
)
LAUNCH_DURATION_S = 5.0
LAUNCH_HOLD_S = (0.5, 4.0)  # switch held and full throttle in this window
LAUNCH_RELEASE_THROTTLE_S = (4.0, 4.3)  # switch released, still full throttle (launch)
LAUNCH_SAMPLE_STEPS = 50  # one row every 50 ms
LAUNCH_COLUMNS = (
    "time_s",
    "speed_rpm",
    "throttle",
    "launchActive",
    "sparkCut",
    "fuelCut",
    "ignition_degBTDC",
    "lateCombustion",
    "catalyst_degC",
    "engineTorque_Nm",
)


def launch_inputs(time_s: float) -> tuple[float, bool]:
    """Throttle and launch switch of the launch scenario at a given time."""
    hold_start, hold_end = LAUNCH_HOLD_S
    release_start, release_end = LAUNCH_RELEASE_THROTTLE_S
    held = hold_start <= time_s < hold_end
    throttle_open = held or release_start <= time_s < release_end
    return (1.0 if throttle_open else 0.0), held


def launch_rows(definition: EngineDefinition) -> list[list[float]]:
    """Simulates the launch scenario without a brake and samples it every 50 ms."""
    tune = replace(Tune.from_tables(definition.tables), launch=LAUNCH_SETTINGS)
    simulation = EngineSimulation(definition, tune)
    steps = round(LAUNCH_DURATION_S / simulation.time_step_s)
    rows: list[list[float]] = []
    for step in range(steps):
        throttle, held = launch_inputs(step * simulation.time_step_s)
        simulation.set_launch_switch(held)
        state = simulation.step(throttle, 0.0)
        if (step + 1) % LAUNCH_SAMPLE_STEPS == 0:
            rows.append(
                [
                    state.time_s,
                    units.rad_s_to_rpm(state.speed_rad_s),
                    state.throttle,
                    1.0 if state.command.launch_active else 0.0,
                    1.0 if state.command.spark_cut else 0.0,
                    1.0 if state.command.fuel_cut else 0.0,
                    state.command.ignition_deg,
                    state.engine.late_combustion_fraction,
                    units.kelvin_to_celsius(state.catalyst_temperature_k),
                    state.engine.brake_torque_nm,
                ]
            )
    return rows


def render_launch_csv(engine_id: str = "i6_30_na") -> str:
    definition = load_engine(engine_path(engine_id))
    buffer = io.StringIO()
    buffer.write(f"# engine: {engine_id} (shared/engines/{engine_id}.json)\n")
    buffer.write(
        f"# free running, launch switch held and full throttle {LAUNCH_HOLD_S[0]}-"
        f"{LAUNCH_HOLD_S[1]} s, released with full throttle until "
        f"{LAUNCH_RELEASE_THROTTLE_S[1]} s, then closed; launch "
        f"{units.rad_s_to_rpm(LAUNCH_SETTINGS.launch_speed_rad_s):.0f} 1/min, retard "
        f"{LAUNCH_SETTINGS.retard_deg} deg; time step 1 ms, row every 50 ms\n"
    )
    buffer.write("# generated by lab: python -m tuning_lab.golden (do not edit by hand)\n")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(LAUNCH_COLUMNS)
    for row in launch_rows(definition):
        writer.writerow([f"{value:.{DECIMALS}f}" for value in row])
    return buffer.getvalue()


def write_launch_golden(directory: Path = GOLDEN_DIR) -> Path:
    path = directory / LAUNCH_FILE_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_launch_csv(), encoding="utf-8")
    return path


